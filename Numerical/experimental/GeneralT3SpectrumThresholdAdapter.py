"""Candidate-basis spectrum and mass-crossing adapter for the 16 ordinary T3 models.

This deliberately REUSES GeneralT3ScalarQuadraticMasses and, for B_-1/C_-1,
GeneralT3MixedScalarMassBasis. It changes no RGEs or matching conditions.

Inputs are running MS-bar quadratic parameters, in GeV**2, in the *declared*
RGBeta spherical basis. These are not pole masses and the RGBeta/Matchete map
is not certified. Quadratic spectra are unbroken-phase trial spectra: Higgs-VEV
shifts, finite self-energies and multiplet-specific threshold projections are
NOT generated by this adapter.

Sampling contract: each RunningMassSample represents the SAME EFT stage;
mu_gev is strictly decreasing; complex mu2 is supplied explicitly, and any
fermion mass list must track the same heavy-eigenstate labels between samples.
Matching is intentionally out of scope: a crossing is a handoff REQUEST, not
permission to delete fields or to set an unknown Wilson correction to zero.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Mapping, Sequence
import math

import numpy as np
from scipy.optimize import brentq

from Numerical.experimental.GeneralT3ScalarQuadraticMasses import (
    REP, load_manifest, quadratic_kind, quadratic_mass_hessian,
)
from Numerical.experimental.GeneralT3MixedScalarMassBasis import MixedDoubletMassBasis

DEFAULT_MANIFEST = (Path(__file__).resolve().parents[2] /
                    'docs/general_scalar_trial_operator_manifest.json')
SPECTRUM_STATUS = 'CandidateSphericalQuadraticMassBasisNotPhysicallyCertified'


def _positive(x: float, name: str) -> float:
    v = float(x)
    if not math.isfinite(v) or v <= 0:
        raise ValueError(f'{name} must be finite and positive')
    return v


def _finite(x: float, name: str) -> float:
    v = float(x)
    if not math.isfinite(v):
        raise ValueError(f'{name} must be finite')
    return v


def _complex(x: complex, name: str) -> complex:
    z = complex(x)
    if not (math.isfinite(z.real) and math.isfinite(z.imag)):
        raise ValueError(f'{name} must be finite')
    return z


@dataclass(frozen=True)
class ScalarMode:
    """One physical mass-squared *branch*, with real-component multiplicity."""
    label: str
    mass_squared_gev2: float
    real_dof: int

    @property
    def mass_gev(self) -> float:
        return math.sqrt(self.mass_squared_gev2) if self.mass_squared_gev2 > 0 else float('nan')


@dataclass(frozen=True)
class ScalarSpectrum:
    model: str
    kind: str
    modes: tuple[ScalarMode, ...]
    hessian_gev2: np.ndarray
    real_eigenvectors: np.ndarray
    mixed_doublet_basis: MixedDoubletMassBasis | None
    convention: str = SPECTRUM_STATUS

    @property
    def positive(self) -> bool:
        return all(mode.mass_squared_gev2 > 0 for mode in self.modes)

    def require_positive(self) -> 'ScalarSpectrum':
        if not self.positive:
            values = [(m.label, m.mass_squared_gev2) for m in self.modes]
            raise ValueError(f'{self.model}: non-positive scalar mass squared: {values}')
        return self

    def by_label(self, label: str) -> ScalarMode:
        matches = [m for m in self.modes if m.label == label]
        if len(matches) != 1:
            raise KeyError(label)
        return matches[0]


def scalar_spectrum(model: str, m_s1_sq_gev2: float,
                    m_s2_sq_gev2: float, mu2_gev2: complex = 0j,
                    *, manifest: Mapping | None = None) -> ScalarSpectrum:
    """Numerical Hessian/eigenvectors plus analytically-labelled scalar branches.

    The 2(dS1+dS2) Cartesian-real eigensystem is unambiguously defined, but
    individual eigenvectors inside degenerate SU(2) multiplets are NOT a unique
    physical field basis. B/C mixed-doublet U is also exposed in its existing
    component convention, independently checked against the real Hessian.
    """
    if manifest is None:
        manifest = load_manifest(DEFAULT_MANIFEST)
    if model not in manifest['models']:
        raise ValueError('Model is not in the verified 16-entry quadratic manifest: '+model)
    kind = quadratic_kind(manifest, model)
    m1 = _finite(m_s1_sq_gev2, 'mS1Sq_gev2')
    m2 = _finite(m_s2_sq_gev2, 'mS2Sq_gev2')
    mu2 = _complex(mu2_gev2, 'mu2_gev2')
    raw = quadratic_mass_hessian(manifest, model, m1, m2, mu2)
    if raw['quadratic_kind'] != kind or not raw['analytic_spectrum_verified']:
        raise RuntimeError('Legacy quadratic spectrum validation failed')
    h = np.asarray(raw['real_scalar_hessian_gev2'], dtype=float)
    eig, u = np.linalg.eigh(h)
    d1, d2, _ = REP[model.split('_')[0]]
    mixed = None
    if kind == 'none':
        branches = [('S1', m1, 2*d1), ('S2', m2, 2*d2)]
    elif kind == 'self_s1':
        branches = [('S1_minus', m1-2*abs(mu2), d1),
                    ('S1_plus', m1+2*abs(mu2), d1), ('S2', m2, 2*d2)]
    elif kind == 'self_s2':
        branches = [('S1', m1, 2*d1), ('S2_minus', m2-2*abs(mu2), d2),
                    ('S2_plus', m2+2*abs(mu2), d2)]
    elif kind == 'mixed':
        # Existing B/C phase convention, field rotation and mass normalization.
        mixed = MixedDoubletMassBasis.build(model, m1, m2, mu2)
        branches = [('X', float(mixed.eigenvalues_sq[0]), 2*d1),
                    ('Y', float(mixed.eigenvalues_sq[1]), 2*d1)]
    else:
        raise RuntimeError('Unknown quadratic kind from legacy registry')
    modes = tuple(ScalarMode(str(label), float(mass2), int(mult))
                  for label, mass2, mult in branches)
    if len(eig) != sum(x.real_dof for x in modes):
        raise RuntimeError('Scalar real-DOF inventory disagrees with Hessian')
    predicted = np.sort(np.concatenate([np.full(x.real_dof, x.mass_squared_gev2)
                                        for x in modes]))
    if not np.allclose(eig, predicted, atol=2e-9, rtol=2e-12):
        raise RuntimeError('Scalar mass branches disagree with the legacy Hessian')
    if not np.allclose(u.T @ h @ u, np.diag(eig), atol=2e-9, rtol=2e-12):
        raise RuntimeError('Scalar Hessian eigenvectors do not diagonalize H')
    return ScalarSpectrum(model, kind, modes, h, u, mixed)


@dataclass(frozen=True)
class ThresholdEvent:
    particle: str
    kind: str
    mass_gev: float
    real_dof: int
    status: str = 'spectrum_only_matching_not_applied'


def ordered_mass_events(spectrum: ScalarSpectrum,
                        fermion_eigenmasses_gev: Sequence[float] = ()) -> tuple[ThresholdEvent, ...]:
    """Sort genuine positive masses at ONE scale (not fixed model labels)."""
    spectrum.require_positive()
    events = [ThresholdEvent('scalar:'+m.label, 'scalar', m.mass_gev, m.real_dof)
              for m in spectrum.modes]
    for i, mass in enumerate(fermion_eigenmasses_gev):
        events.append(ThresholdEvent(f'fermion:{i}', 'fermion',
                                     _positive(mass, f'fermion[{i}]'), 0))
    return tuple(sorted(events, key=lambda e: (-e.mass_gev, e.kind, e.particle)))


@dataclass(frozen=True)
class RunningMassSample:
    mu_gev: float
    m_s1_sq_gev2: float
    m_s2_sq_gev2: float
    mu2_gev2: complex = 0j
    fermion_eigenmasses_gev: tuple[float, ...] = ()

    def validated(self) -> 'RunningMassSample':
        _positive(self.mu_gev, 'mu_gev')
        _finite(self.m_s1_sq_gev2, 'mS1Sq_gev2')
        _finite(self.m_s2_sq_gev2, 'mS2Sq_gev2')
        _complex(self.mu2_gev2, 'mu2_gev2')
        for i, m in enumerate(self.fermion_eigenmasses_gev):
            _positive(m, f'fermion_eigenmasses_gev[{i}]')
        return self


@dataclass(frozen=True)
class ThresholdCrossing:
    particle: str
    kind: str
    scale_gev: float
    real_dof: int
    relative_mass_scale_residual: float
    method: str = 'linear running quadratic entries in ln(mu); numerical root'
    status: str = 'matching_required_not_applied'


def find_mass_crossings(model: str, samples: Sequence[RunningMassSample],
                        *, manifest: Mapping | None = None) -> tuple[ThresholdCrossing, ...]:
    """Locate mu=M(mu) on the supplied running trajectory, largest mu first.

    Each sample is within ONE EFT stage. Interpolate underlying scalar m**2
    parameters and complex mu2 linearly in ln(mu), then re-diagonalize at each
    trial root; fermion *masses* interpolate linearly in ln(mu). Does not
    interpolate pre-diagonalized scalar eigenmasses. All crossings are reported;
    if no root is bracketed no threshold is asserted. A branch with multiple
    crossings is rejected because its decoupling history is ambiguous.
    """
    if manifest is None:
        manifest = load_manifest(DEFAULT_MANIFEST)
    src = tuple(s.validated() for s in samples)
    if len(src) < 2:
        raise ValueError('At least two running mass samples required')
    logs = np.log([s.mu_gev for s in src])
    if not np.all(np.diff(logs) < 0):
        raise ValueError('Mass samples must be strictly descending in mu')
    nferm = len(src[0].fermion_eigenmasses_gev)
    if any(len(s.fermion_eigenmasses_gev) != nferm for s in src):
        raise ValueError('Fermion eigenstate inventory changes inside one EFT stage')
    first = scalar_spectrum(model, src[0].m_s1_sq_gev2,
                            src[0].m_s2_sq_gev2, src[0].mu2_gev2,
                            manifest=manifest).require_positive()
    specs = [first]
    for s in src[1:]:
        sp = scalar_spectrum(model, s.m_s1_sq_gev2, s.m_s2_sq_gev2,
                             s.mu2_gev2, manifest=manifest).require_positive()
        if tuple(m.label for m in sp.modes) != tuple(m.label for m in first.modes):
            raise RuntimeError('Scalar mass branch identity changed within stage')
        specs.append(sp)
    keys = [(f'scalar:{m.label}', 'scalar', m.real_dof) for m in first.modes]
    keys += [(f'fermion:{i}', 'fermion', 0) for i in range(nferm)]

    def mass2_at(j: int, t: float, key: str) -> float:
        a,b = src[j],src[j+1]
        w = (t-logs[j])/(logs[j+1]-logs[j])
        if key.startswith('fermion:'):
            i = int(key.split(':')[1])
            mass = (1-w)*a.fermion_eigenmasses_gev[i] + w*b.fermion_eigenmasses_gev[i]
            return float(mass)**2
        sp = scalar_spectrum(model,
               (1-w)*a.m_s1_sq_gev2+w*b.m_s1_sq_gev2,
               (1-w)*a.m_s2_sq_gev2+w*b.m_s2_sq_gev2,
               (1-w)*a.mu2_gev2+w*b.mu2_gev2, manifest=manifest)
        return sp.by_label(key.split(':',1)[1]).mass_squared_gev2

    roots = []
    for key,kind,dof in keys:
        found = []
        for j in range(len(src)-1):
            left, right = float(logs[j]), float(logs[j+1])
            f_left = mass2_at(j,left,key)-math.exp(2*left)
            f_right = mass2_at(j,right,key)-math.exp(2*right)
            # A descending-scale decoupling must run from mu > M to mu < M.
            if f_left > 0 and f_right < 0:
                raise ValueError(f'{key}: inverse crossing (possible recoupling)')
            if f_left <= 0 <= f_right:
                t = float(brentq(lambda z: mass2_at(j,z,key)-math.exp(2*z),
                                  right,left,xtol=2e-13)) if f_left*f_right < 0 else (
                                      left if f_left == 0 else right)
                if not any(abs(t-u) < 1e-10 for u in found):
                    found.append(t)
        if len(found) > 1:
            raise ValueError(f'{key}: multiple crossings in the same EFT stage')
        if found:
            t = found[0]
            j = next((i for i in range(len(logs)-1)
                      if float(logs[i+1])-1e-10 <= t <= float(logs[i])+1e-10), None)
            if j is None:
                raise RuntimeError('Threshold root outside sampled stage')
            scale = math.exp(t)
            resid = abs(mass2_at(j,t,key)/scale**2-1.)
            if resid > 1e-9:
                raise RuntimeError(f'{key}: threshold root residual {resid}')
            roots.append(ThresholdCrossing(key,kind,scale,dof,float(resid)))
    return tuple(sorted(roots,key=lambda x: (-x.scale_gev,x.kind,x.particle)))
