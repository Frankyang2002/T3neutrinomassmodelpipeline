"""Read-only B/C restricted benchmark comparison and SM-only diagnostic.

Never identifies a historical EFT1 Wilson trajectory with the new five-mass UV
trajectory. No physical sequential EFT matching is generated by this module.
"""
from __future__ import annotations
import math
from typing import Mapping
import numpy as np

MODELS=('B_-1','C_-1')
STATUS='FiveMassSMProxyAndHistoricalEFT1ComparedSameTrajectoryWilsonMissing'


def require(ok,msg):
    if not ok:raise ValueError('B/C final benchmark: '+msg)


def sorted_masses(values,label):
    a=np.asarray(values,dtype=float)
    require(a.shape==(3,) and np.isfinite(a).all() and np.all(a>=0) and
            np.all(np.diff(a)<=1e-14),label+' must be three descending finite masses')
    return a


def validate_grouped(model:str, report:Mapping)->dict:
    require(model in MODELS,'invalid model')
    require(report.get('format')=='t3-bc-single-eft1-grouped-scalar-conditional-v1' and
            report.get('status')=='HistoricalEFT1CoupledWilsonGroupedScalarCandidateNoFiniteMatching',
            'historical grouped report status changed')
    require(report.get('same_trajectory_as_batch1_five_mass_running_verified') is False and
            report.get('batch1_boundary_numerically_inserted') is False and
            report.get('one_intermediate_EFT_only') is True and
            report.get('finite_scalar_threshold_matching_computed') is False and
            report.get('physical_C5_certified') is False,
            'upstream grouped report provenance/certification changed')
    row=report['models'][model]
    require(row.get('model')==model and row.get('physical_C5_certified') is False and
            row.get('full_matching_certified') is False and
            row.get('finite_scalar_threshold_correction')=='UNKNOWN_NOT_ZERO',
            'historical candidate cannot be treated as physical')
    mu_f=float(row['mu_F_gev']);mu_s=float(row['mu_S_grouped_gev'])
    require(math.isfinite(mu_f) and math.isfinite(mu_s) and mu_f>mu_s>0,
            'historical threshold order failed')
    masses=sorted_masses(row['candidate_masses_ev_descending'],'historical masses')
    return {'mu_F_gev':mu_f,'mu_S_gev':mu_s,'masses_ev_descending':masses.tolist(),
            'provenance':'historical continuous_v1 EFT1, different UV benchmark',
            'same_five_mass_trajectory':False,'finite_scalar_matching':False}


def compare(model:str, grouped:Mapping, running:Mapping, proxy_a:Mapping,proxy_b:Mapping)->dict:
    from Numerical.experimental.T3BCMegaPhysicalBridge import unpack_matrix,relative
    require(model in MODELS and running.get('model')==model,'running model mismatch')
    require(running.get('physical_C5_certified') is False and
            running.get('full_fermion_X_Y_sequential_RG_transport') is False,
            'running source incorrectly certified')
    require(proxy_a.get('status')=='SMOnlyOneScaleReferenceComputedNotSequentialEFT' and
            proxy_b.get('status')=='SMOnlyOneScaleReferenceComputedNotSequentialEFT' and
            proxy_a.get('model')==proxy_b.get('model')==model,
            'SM-only proxy status mismatch')
    for p in (proxy_a,proxy_b):
        require(p.get('actual_active_F_X_Y_in_interval_ignored') is True and
                p.get('complete_EFT1_EFT2_running') is False and
                p.get('physical_neutrino_prediction') is False and
                p.get('finite_matching_included') is False,
                'SM-only proxy flags changed')
    c_a=unpack_matrix(proxy_a['reference_C5_at_low_gev_inverse'])
    c_b=unpack_matrix(proxy_b['reference_C5_at_low_gev_inverse'])
    conv=relative(c_a,c_b)
    require(conv<1e-5,'SM-only proxy convergence failed')
    proxy=sorted_masses(proxy_a['SM_only_100gev_reference']['masses_descending_ev'],
                        'SM-only proxy spectrum')
    one=sorted_masses(running['reference_mnu_singular_ev_descending_NOT_PHYSICAL'],
                      'one-scale spectrum')
    hist=sorted_masses(grouped['masses_ev_descending'],'historical EFT1 spectrum')
    require(float(proxy_a['initial_mu_gev'])==1e5 and float(proxy_a['low_mu_gev'])==100.,
            'SM-only scale mismatch')
    return {'model':model,'status':STATUS,
      'one_scale_candidate_at_1e5_gev_masses_ev_descending':one.tolist(),
      'same_five_mass_UV_input_SM_only_100gev_proxy_masses_ev_descending':proxy.tolist(),
      'historical_EFT1_grouped_candidate_masses_ev_descending':hist.tolist(),
      'SM_only_proxy_solver_rtol_pair':[float(proxy_a['solver_rtol']),float(proxy_b['solver_rtol'])],
      'SM_only_proxy_convergence_relative_C5':conv,
      'same_UV_SM_only_change_relative_C5':float(proxy_a['relative_C5_change_SM_only_proxy']),
      'historical_vs_five_mass_proxy_mass_difference_ev':(hist-proxy).tolist(),
      'historical_vs_five_mass_proxy_comparison_is_physical_running_effect':False,
      'five_mass_source_EFT1_wilson_boundary_transferred':False,
      'five_mass_source_EFT1_wilson_RGE_evolved':False,
      'one_intermediate_EFT_only':True,
      'same_trajectory_sequential_C5_computed':False,
      'full_finite_scalar_matching_computed':False,
      'physical_C5_certified':False,
      'physical_neutrino_masses_certified':False,
      'next_missing_operation':'Evolve LLSS / full Wilson tensor with five-mass F threshold boundary using five-mass EFT1 scalar history; then grouped scalar finite matching'}
