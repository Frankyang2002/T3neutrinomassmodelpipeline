"""Fully coupled *RGBeta-coordinate* UV evolution of ordinary T3 models.

All exported beta functions (including generic complex quartics and independent
neutral-scalar Yukawas) are dynamically packed. This intentionally does not
modify the legacy T3UVState/UVRunner or claim a Matchete coupling conversion.
The endpoint must stay above all heavy thresholds. No threshold matching.

Requires the 16 opt-in general RGBeta JSON files already generated by
scripts/RunT3ExtraYukawaStack.py --all.
"""
from __future__ import annotations

import dataclasses
import json
import math
from pathlib import Path
from typing import Any, Mapping

import numpy as np
from scipy.integrate import solve_ivp

ROOT = Path(__file__).resolve().parents[2]
REPORTS = ROOT / 'Reports/output/workstream_a/integrated_general_yukawa_uv/native'
CONFIGS = ROOT / 'Numerical/benchmarks/fitted_reference'
OUTPUT = ROOT / 'Reports/output/workstream_a/full_coupled_general_yukawa_uv'

# This catalogue matches the independently verified 16-model RG exporter.
SPECS = {
    'A_m4':(1,3,2,-4),'A_m2':(1,3,2,-2),'A_p0':(1,3,2,0),
    'B_m3':(2,2,1,-3),'B_m1':(2,2,1,-1),'B_p1':(2,2,1,1),
    'C_m3':(2,2,3,-3),'C_m1':(2,2,3,-1),'C_p1':(2,2,3,1),
    'D_m2':(3,1,2,-2),'D_p0':(3,1,2,0),'D_p2':(3,1,2,2),
    'E_m4':(3,3,2,-4),'E_m2':(3,3,2,-2),'E_p0':(3,3,2,0),'E_p2':(3,3,2,2),
}
EXTRAS = {name: ('y1Conj' if spec[3] == 0 else 'y2Conj')
          for name,spec in SPECS.items() if name[0] in 'ADE' and spec[3] in (0,-2)}
MATRIX = frozenset(('yu','yd','ye','y1','y2','MF','y1Conj','y2Conj'))
REAL = frozenset(('gY','g2','g3','lambdaH','mS1Sq','mS2Sq','lambdaS1',
                  'lambdaS2','lambdaH1','lambdaH2','lambda12',
                  'lambdaH1Adj','lambdaH2Adj','lambdaS1Adj','lambdaS2Adj',
                  'lambda12Adj','lambda12Cross'))
# The six B/C alpha=-1 optional structures and all generated quartics are
# independently registered with SelfConjugate->False.
COMPLEX = frozenset(('lambdaT3','lambdaHHdagS2S2',
                     'lambdaHHdagS1barS1bar','lambdaS1bar2S2bar2',
                     'lambdaS1barS2S2bar2','lambdaS1S1bar2S2bar',
                     'lambdaHHdagS1barS2barCross'))
BETA_CONVENTION='16*pi^2*dX/dln(mu); gauge BetaTerm divided by 2*g'


def require(ok: bool, msg: str) -> None:
    if not ok: raise ValueError(msg)


def scalar(raw: Any) -> complex:
    if isinstance(raw,dict):
        require(set(raw)=={'real','imag'},'Expected scalar real/imag keys')
        z=complex(float(raw['real']),float(raw['imag']))
    else:z=complex(raw)
    require(bool(np.isfinite([z.real,z.imag]).all()),'Nonfinite scalar input')
    return z


def matrix(raw: Any) -> np.ndarray:
    if isinstance(raw,dict):
        require(set(raw)=={'real','imag'},'Expected matrix real/imag keys')
        re=np.asarray(raw['real'],dtype=float)
        im=np.asarray(raw['imag'],dtype=float)
        require(re.shape==(3,3) and im.shape==re.shape,'Expected exact 3x3 matrix')
        x=re+1j*im
    else:x=np.asarray(raw,dtype=complex)
    require(x.shape==(3,3) and bool(np.isfinite(x).all()),'Expected finite 3x3 matrix')
    return x.copy()


def kind(name: str) -> str:
    if name in MATRIX:return 'matrix'
    if name in REAL:return 'real'
    if name in COMPLEX or name.startswith('lambdaT3GeneralQ'):return 'complex'
    raise ValueError(f'Unclassified RGBeta state key {name!r}: add explicit type after source verification')


def load_case(model: str, report_dir: Path=REPORTS, config_dir: Path=CONFIGS):
    require(model in SPECS,'Unknown model '+model)
    dims=SPECS[model]
    path=report_dir/(model+'.json')
    require(path.is_file(),f'Missing RGBeta report: {path}')
    payload=json.loads(path.read_text(encoding='utf-8-sig'))
    require(isinstance(payload,dict) and payload.get('status')=='Success',f'{model}: RGBeta not successful')
    meta=payload.get('metadata',{})
    require(isinstance(meta,dict),'RGBeta metadata missing')
    for name,value in zip(('dS1','dS2','dF','alpha'),dims):
        require(meta.get(name)==value,f'{model}: wrong metadata {name}')
    require(meta.get('SharedScalar') is False and meta.get('MajoranaFermion')==(dims[3]==-1),
            f'{model}: incorrect fermion/representation metadata')
    require(meta.get('GeneralScalarStage')=='UV' and meta.get('GeneralScalarQuarticBetaBasis')=='RGBetaFullQuarticProjection',
            f'{model}: full general quartic projection missing')
    require(meta.get('ReportBetaConvention')==BETA_CONVENTION,'Unsupported beta convention')
    betas=payload.get('report_betas')
    require(isinstance(betas,dict) and set(betas)==set(payload.get('betas',{})),
            'Missing or mismatched RGBeta beta dictionaries')
    expected_extra={EXTRAS[model]} if model in EXTRAS else set()
    require(set(betas)&{'y1Conj','y2Conj'}==expected_extra,f'{model}: wrong extra-Yukawa beta keys')
    for k,v in betas.items():
        kind(k)
        require(isinstance(v,str) and v.strip() and 'BetaTerm[' not in v and '$Failed' not in v,
                f'{model}: unresolved beta {k}')
    cfg=config_dir/(f'T3_dS1_{dims[0]}_dS2_{dims[1]}_dF_{dims[2]}_alpha_'+
                    (f'm{-dims[3]}' if dims[3]<0 else f'p{dims[3]}')+'.json')
    require(cfg.is_file(),f'Missing reference configuration: {cfg}')
    config=json.loads(cfg.read_text(encoding='utf-8-sig'))
    rep=config['representation']
    require(tuple(rep[k] for k in ('d_s1','d_s2','d_f','alpha'))==dims and not rep.get('shared_scalar',False),
            'Reference representation mismatch')
    return payload,config


def prepare_state(model: str,payload:Mapping[str,Any],config:Mapping[str,Any],seed_factor:float=0.3) -> dict:
    require(math.isfinite(seed_factor) and seed_factor>=0,'Seed factor must be nonnegative finite')
    c=config['base_state']; sm=c['sm']; ordinary=c['ordinary']; state={}
    norms=[np.max(np.abs(matrix(ordinary[k]))) for k in ('y1','y2')]
    seed_norm=max(float(max(norms)),1e-6)
    seed=np.array([[1,0.2+0.15j,-0.1],[0.3,0.8,0.2j],[-0.05j,0.1,0.6]],dtype=complex)
    for name in payload['report_betas']:
        typ=kind(name)
        if name in sm:raw=sm[name]
        elif name in ordinary and ordinary[name] is not None:raw=ordinary[name]
        elif name in {'y1Conj','y2Conj'}:raw=seed_factor*seed_norm*seed
        elif name.startswith('lambdaT3GeneralQ'):raw=0j
        elif name in REAL:raw=0.
        elif name in COMPLEX:raw=0j
        else:raise ValueError(f'{model}: no input data for beta variable {name}')
        if typ=='matrix':state[name]=matrix(raw)
        elif typ=='real':
            z=scalar(raw)
            require(abs(z.imag)<=1e-14,'Real coupling '+name+' has nonzero imaginary input')
            state[name]=float(z.real)
        else:state[name]=scalar(raw)
    return state


@dataclasses.dataclass(frozen=True)
class Block:
    name:str
    kind:str
    start:int
    stop:int


class DynamicLayout:
    def __init__(self,names):
        self.blocks=[]; n=0
        for name in names:
            typ=kind(name); width={'real':1,'complex':2,'matrix':18}[typ]
            self.blocks.append(Block(name,typ,n,n+width));n+=width
        self.size=n;self.names=tuple(names)
        require(len(set(self.names))==len(self.names),'Duplicate beta names')

    def pack(self,values:Mapping[str,Any], *, beta=False) -> np.ndarray:
        require(set(values)==set(self.names),'State/beta name mismatch')
        v=np.empty(self.size,dtype=float)
        for b in self.blocks:
            if b.kind=='matrix':
                z=matrix(values[b.name]); a=np.r_[z.real.ravel(),z.imag.ravel()]
            else:
                z=scalar(values[b.name]);
                if b.kind=='real':
                    require(abs(z.imag)<=1e-10*max(1.0,abs(z.real)),
                            f'{b.name}: beta of real variable has imaginary component {z.imag}')
                    a=np.array([z.real],dtype=float)
                else:a=np.array([z.real,z.imag],dtype=float)
            v[b.start:b.stop]=a
        require(bool(np.isfinite(v).all()),'Nonfinite vector')
        return v

    def unpack(self,raw:np.ndarray)->dict:
        y=np.asarray(raw,dtype=float)
        require(y.shape==(self.size,) and bool(np.isfinite(y).all()),'Bad solver vector')
        result={}
        for b in self.blocks:
            a=y[b.start:b.stop]
            if b.kind=='matrix':result[b.name]=a[:9].reshape(3,3)+1j*a[9:].reshape(3,3)
            elif b.kind=='real':result[b.name]=float(a[0])
            else:result[b.name]=complex(*a)
        return result


def pack_derivative(layout:DynamicLayout,evaluated:dict)->np.ndarray:
    return layout.pack(evaluated,beta=True)/(16*math.pi**2)


def evaluate_betas(expressions:Mapping[str,str], values:Mapping[str,Any])->dict:
    """Evaluate exact exported InputForm using the repository parser.

    The general quartic projection can contain square-root and complex
    coefficients not present in the baseline runner. Extend only named
    elementary scalar operations, never permit arbitrary Python evaluation.
    """
    from Numerical.core import RGBetaEvaluator as parser
    env=dict(values, I=1j, Pi=math.pi, E=math.e)

    class GeneralParser(parser._Parser):
        def call_function(self, name, args):
            funcs={'Sqrt':np.emath.sqrt,'Abs':np.abs,'Re':np.real,'Im':np.imag,
                   'Conjugate':np.conjugate,'Exp':np.exp,'Log':np.log,
                   'Sin':np.sin,'Cos':np.cos}
            if name in funcs:
                self._require_arity(name,args,1)
                return funcs[name](args[0])
            if name=='Complex':
                self._require_arity(name,args,2)
                require(not isinstance(args[0],np.ndarray) and not isinstance(args[1],np.ndarray),
                        'Complex[...] expects scalar numbers')
                return complex(args[0])+1j*complex(args[1])
            if name=='ConjugateTranspose':
                self._require_arity(name,args,1)
                return np.conjugate(args[0]).T if isinstance(args[0],np.ndarray) else np.conjugate(args[0])
            return super().call_function(name,args)

    output={}
    for key,expr in expressions.items():
        try:output[key]=GeneralParser(str(expr),env).parse()
        except Exception as exc:
            raise ValueError(f'Failed RGBeta InputForm beta {key}: {exc}') from exc
    return output


def integrate(payload:dict, initial:dict, uv:float, endpoint:float, *,
              n_save:int=9,rtol:float=1e-7,atol:float=1e-10,
              evaluator=evaluate_betas):
    require(uv>endpoint>0 and bool(np.isfinite([uv,endpoint]).all()),'Invalid scale interval')
    require(2<=n_save<=1001,'Save count out of range')
    layout=DynamicLayout(payload['report_betas'].keys())
    x0=layout.pack(initial)
    equations=payload['report_betas']
    is_majorana=bool(payload.get('metadata',{}).get('MajoranaFermion',False))
    if is_majorana:
        mf=initial['MF']
        require(np.allclose(mf,mf.T,rtol=1e-10,atol=1e-9),
                'Majorana initial mass matrix is not symmetric')
    def rhs(t,x):
        state=layout.unpack(x)
        if is_majorana:
            # Symmetric Majorana mass is a constrained subspace. Symmetrize
            # only numerical drift, and reject a genuinely non-symmetric beta.
            state['MF']=.5*(state['MF']+state['MF'].T)
        betas=evaluator(equations,state)
        if is_majorana:
            m_beta=matrix(betas['MF'])
            require(norm(m_beta-m_beta.T)<=1e-7*max(1.,norm(m_beta)),
                    'Majorana MF beta breaks complex symmetric mass constraint')
            betas['MF']=.5*(m_beta+m_beta.T)
        return pack_derivative(layout,betas)
    start_beta=rhs(math.log(uv),x0)
    require(bool(np.isfinite(start_beta).all()),'Initial nonfinite derivative')
    # Evaluate in t=ln(mu), including both endpoints.
    t_eval=np.linspace(math.log(uv),math.log(endpoint),n_save)
    sol=solve_ivp(rhs,(t_eval[0],t_eval[-1]),x0,method='DOP853',t_eval=t_eval,
                  rtol=rtol,atol=atol)
    require(sol.success and len(sol.t)==n_save,'Coupled UV ODE failed: '+str(sol.message))
    require(bool(np.isfinite(sol.y).all()),'Nonfinite integrated solution')
    if is_majorana:
        mfblock=next(b for b in layout.blocks if b.name=='MF')
        n=9
        for j in range(sol.y.shape[1]):
            x=sol.y[mfblock.start:mfblock.stop,j]
            for offset in (0,n):
                part=x[offset:offset+n].reshape(3,3)
                part[:]=.5*(part+part.T)
    return layout,sol,start_beta


def endpoint_for(config:Mapping[str,Any],values:Mapping[str,Any], *, factor:float=1.5)->tuple[float,float]:
    require(factor>1.0 and math.isfinite(factor),'Endpoint buffer must exceed 1')
    initial=float(config['base_state']['mu_gev'])
    threshold=float(config['scales']['mu_fermion_threshold_gev'])
    heavy=float(np.max(np.linalg.svd(matrix(values['MF']),compute_uv=False)))
    endpoint=factor*max(threshold,heavy)
    require(initial>endpoint>0,'UV interval invalid or no room above heavy thresholds')
    return initial,endpoint


def encode(z:Any)->dict|float:
    if isinstance(z,np.ndarray):
        return {'real':z.real.tolist(),'imag':z.imag.tolist()}
    z=complex(z)
    return {'real':float(z.real),'imag':float(z.imag)}


def norm(z:Any)->float:
    return float(np.linalg.norm(np.asarray(z,dtype=complex)))


def run_model(model:str, *, seed_factor:float=0.3, n_save:int=9,
              report_dir:Path=REPORTS, config_dir:Path=CONFIGS,
              output:Path|None=None, evaluator=evaluate_betas)->dict:
    payload,config=load_case(model,report_dir,config_dir)
    state=prepare_state(model,payload,config,seed_factor)
    initial_scale,final_scale=endpoint_for(config,state)
    layout,sol,initial_beta=integrate(payload,state,initial_scale,final_scale,
                                      n_save=n_save,evaluator=evaluator)
    end=layout.unpack(sol.y[:,-1])
    final_heavy_mass=float(np.max(np.linalg.svd(end['MF'],compute_uv=False)))
    require(final_scale>1.05*final_heavy_mass,
            f'{model}: evolved heavy mass {final_heavy_mass:.6g} GeV crosses the UV-only integration endpoint {final_scale:.6g} GeV')
    extra=EXTRAS.get(model)
    comparison=None
    if extra is not None:
        # The full model is evolved again with the extra Yukawa initially zero.
        # No assumption is made that this subspace remains RG invariant.
        zero={k:(v.copy() if isinstance(v,np.ndarray) else v) for k,v in state.items()}
        zero[extra]=np.zeros((3,3),dtype=complex)
        _,control,control_beta=integrate(payload,zero,initial_scale,final_scale,
                                         n_save=n_save,evaluator=evaluator)
        control_end=layout.unpack(control.y[:,-1])
        comparison={
            'beta_extra_at_zero_frobenius':norm(layout.unpack(control_beta*(16*math.pi**2))[extra]),
            'extra_final_zero_seed_frobenius':norm(control_end[extra]),
            'extra_final_seeded_frobenius':norm(end[extra]),
            'delta_ordinary_y1_endpoint_frobenius':norm(end['y1']-control_end['y1']),
            'delta_ordinary_y2_endpoint_frobenius':norm(end['y2']-control_end['y2']),
            'delta_MF_endpoint_frobenius_gev':norm(end['MF']-control_end['MF']),
            'delta_state_endpoint_euclidean':float(np.linalg.norm(sol.y[:,-1]-control.y[:,-1])),
            'control_nfev':int(control.nfev),
            'zero_extra_yukawa_is_not_assumed_invariant':True,
        }
    # All dimensionful and quartic couplings are part of the same RHS.
    trajectories=[]
    for j,t in enumerate(sol.t):
        value=layout.unpack(sol.y[:,j])
        trajectories.append({
            'mu_gev':float(np.exp(t)),
            'coupling_frobenius_or_absolute':{name:norm(value[name]) for name in layout.names},
            'yukawa_matrices':{k:encode(value[k]) for k in ('y1','y2',extra) if k is not None},
            'MF_matrix_gev':encode(value['MF']),
        })
    result={
        'status':'CoupledGeneralYukawaRGBetaOnlyUVPassed',
        'model':model,'dimensions_alpha':list(SPECS[model]),'extra_yukawa':extra,
        'alpha':SPECS[model][3],
        'mu_initial_gev':initial_scale,'mu_final_gev':final_scale,
        'n_coupling_blocks':len(layout.names),'real_ode_size':layout.size,
        'active_couplings':list(layout.names),'nfev':int(sol.nfev),
        'rtol':1e-7,'atol':1e-10,'seed_factor_relative_to_max_yukawa':seed_factor,
        'initial_beta_derivative_euclidean':float(np.linalg.norm(initial_beta)),
        'relative_changes':{k:float(norm(end[k]-state[k])/max(norm(state[k]),1e-30))
                            for k in ('y1','y2','MF')},
        'initial_linearized_vs_coupled_relative_error':{
            k:float(norm(end[k]-state[k] -
                         layout.unpack(initial_beta*(math.log(final_scale/initial_scale)))[k]) /
                    max(norm(end[k]-state[k]),1e-30))
            for k in ('y1','y2','MF',extra) if k is not None},
        'final_heavy_mass_max_singular_gev':final_heavy_mass,
        'endpoint_above_evolved_heavy_mass':True,
        'final_scalar_masses_sq_gev2':{'mS1Sq':float(end['mS1Sq']),
                                        'mS2Sq':float(end['mS2Sq'])},
        'final_scalar_mass_sq_positive':bool(end['mS1Sq']>0 and end['mS2Sq']>0),
        'initial_extra_matrix':encode(state[extra]) if extra else None,
        'final_extra_matrix':encode(end[extra]) if extra else None,
        'seeded_vs_zero_control':comparison,
        'sampled_trajectory':trajectories,
        'full_coupled_uv_beta_vector_evolved':True,
        'general_scalar_quartic_beta_basis':'RGBetaFullQuarticProjection',
        'basis':'RGBeta-only illustrative coordinates; legacy fitted reference numerical values used as unconverted inputs',
        'physical_matchete_rgbeta_dictionary_certified':False,
        'threshold_matching_performed':False,
        'extended_neutrino_mass_prediction_performed':False,
    }
    if output is not None:
        output.parent.mkdir(parents=True,exist_ok=True)
        temp=output.with_name(output.name+'.tmp')
        temp.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
        temp.replace(output)
    return result


def self_test():
    require(len(SPECS)==16 and len(EXTRAS)==6,'Catalogue broken')
    names=['gY','y1','y1Conj','MF','lambdaT3','lambdaT3GeneralQdemo']
    lay=DynamicLayout(names)
    a={'gY':0.4,'y1':np.eye(3)*0.01,'y1Conj':np.eye(3)*(.03+.02j),
       'MF':np.eye(3)*1e5,'lambdaT3':.1+.2j,'lambdaT3GeneralQdemo':0j}
    b=lay.unpack(lay.pack(a))
    for name in names:require(np.allclose(np.asarray(a[name]),np.asarray(b[name])),'Layout round trip '+name)
    assert lay.size==1+18*3+2*2
    for bad in ['unknownX','lambdaT3UnregisteredExtra']:
        try:kind(bad)
        except ValueError:pass
        else:raise AssertionError('Unknown coupling classification bypassed')
    for bad in [np.zeros((2,2)),np.zeros((3,3,1))]:
        try:matrix(bad)
        except ValueError:pass
        else:raise AssertionError('Invalid matrix accepted')
    try:lay.pack(dict(a,gY=1+0.01j))
    except ValueError:pass
    else:raise AssertionError('Complex real-scalar accepted')
    # Synthetic all-channel coupled system with exactly solvable trajectories.
    # This tests integration and dynamic extra beta packing, not RGBeta math.
    pilot={'report_betas':{k:'unused' for k in names}}
    def evaluator(eq,env):return {k:(16*math.pi**2)*env[k] for k in eq}
    lay2,solution,beta0=integrate(pilot,a,1000.,100.,n_save=7,evaluator=evaluator)
    expected=lay2.pack(a)*.1
    require(np.allclose(solution.y[:,-1],expected,rtol=2e-7,atol=1e-7),
            'Exact exponential ODE failed')
    require(np.allclose(beta0,lay2.pack(a)),'Derivative convention wrong')
    zero=dict(a,y1Conj=np.zeros((3,3),complex))
    _,control,_=integrate(pilot,zero,1000.,100.,n_save=3,evaluator=evaluator)
    require(np.allclose(lay2.unpack(control.y[:,-1])['y1Conj'],0),'Zero-control ODE failed')
    # On the user's repository, also test compatibility with the real
    # Numerical/core/RGBetaEvaluator.py InputForm tokeniser.
    try:
        from Numerical.core import RGBetaEvaluator as _native_parser
    except ModuleNotFoundError:
        print('INFO: repository InputForm parser not available in isolated test; live parser test deferred')
    else:
        samples={'sqrt':'Sqrt[2]','imag':'I*lambdaT3',
                 'complex':'Complex[0,1]*lambdaT3',
                 'trace':'Tr[Matrix[y1]]','bar':'Bar[lambdaT3]'}
        parsed=evaluate_betas(samples,{'lambdaT3':1+.5j,'y1':np.eye(3,dtype=complex)})
        require(abs(parsed['sqrt']-math.sqrt(2))<1e-12,'InputForm sqrt head failed')
        require(abs(parsed['imag']-1j*(1+.5j))<1e-12,'InputForm imaginary unit failed')
        require(abs(parsed['complex']-1j*(1+.5j))<1e-12,'InputForm Complex head failed')
        require(abs(parsed['trace']-3)<1e-12,'InputForm matrix trace failed')
        require(abs(parsed['bar']-(1-.5j))<1e-12,'InputForm conjugate failed')
    print('PASS: 16-model catalogue; 6 extras; full dynamic complex layout; real/complex negative controls; exact ODE solution')


if __name__=='__main__':
    self_test()
