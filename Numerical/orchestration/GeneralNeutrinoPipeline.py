"""General-T3 numerical pipeline with explicitly supplied matching kernels.

Reuses the established UV, scalar-only EFT, SM+Weinberg and observable solvers.
The physical matching kernels are input data, not generated by this program.
In particular, supplying generic kernels does not certify the effects of new
scalar quartics/bilinears or their physical field-basis normalization.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Mapping

import numpy as np

CHANNEL_NAMES = frozenset(("y1", "y2", "y1Conj", "y2Conj"))


def decode(value: Any) -> Any:
    """Decode the repository's JSON complex representation."""
    if isinstance(value, Mapping) and set(value) == {"real", "imag"}:
        return complex(float(value["real"]), float(value["imag"]))
    if isinstance(value, list):
        return [decode(x) for x in value]
    return value


def encode(value: Any) -> Any:
    if isinstance(value, np.ndarray):
        return encode(value.tolist())
    if isinstance(value, np.generic):
        return encode(value.item())
    if isinstance(value, complex):
        return {"real": float(value.real), "imag": float(value.imag)}
    if isinstance(value, (list, tuple)):
        return [encode(x) for x in value]
    if isinstance(value, dict):
        return {str(k): encode(v) for k, v in value.items()}
    return value


def construct_c5_from_kernels(
    running_at_f: Mapping[str, Any],
    matching: Mapping[str, Any],
) -> np.ndarray:
    """Sum supplied kernels using the existing T3 Majorana flavor convention.

    A channel is {left, right, kernel_gev_inv}, with a kernel value for each
    heavy flavour (or one scalar value applied to all three). Each channel
    adds k_r (conj(Y_left[i,r])*conj(Y_right[j,r]) + i<->j).

    These kernels must ALREADY include all mass factors, group factors, scalar
    mixing, vertex normalization and loop factors from physical matching.
    """
    if matching.get("schema") != "t3-explicit-matching-kernels-v1":
        raise ValueError("Matching JSON must declare t3-explicit-matching-kernels-v1")
    channels = matching.get("channels")
    if not isinstance(channels, list) or not channels:
        raise ValueError("At least one explicitly matched Yukawa channel required")
    available = {}
    for name in CHANNEL_NAMES.intersection(running_at_f):
        matrix = np.asarray(decode(running_at_f[name]), dtype=complex)
        if matrix.shape != (3, 3) or not np.all(np.isfinite(matrix)):
            raise ValueError(f"Invalid Yukawa matrix {name}")
        available[name] = matrix
    c5 = np.zeros((3, 3), dtype=complex)
    for index, row in enumerate(channels):
        if not isinstance(row, Mapping):
            raise ValueError(f"Channel {index} must be an object")
        left, right = row.get("left"), row.get("right")
        if left not in available or right not in available:
            raise ValueError(f"Channel {index}: Yukawa name not in this model: {left}, {right}")
        raw = decode(row.get("kernel_gev_inv"))
        kernel = np.asarray(raw, dtype=complex)
        if kernel.shape == ():
            kernel = np.full(3, complex(kernel))
        if kernel.shape != (3,) or not np.all(np.isfinite(kernel)):
            raise ValueError(f"Channel {index}: kernel_gev_inv must have 1 or 3 finite values")
        yl = np.conjugate(available[left]); yr = np.conjugate(available[right])
        c5 += (yl * kernel[np.newaxis, :]) @ yr.T
        c5 += (yr * kernel[np.newaxis, :]) @ yl.T
    if not np.all(np.isfinite(c5)):
        raise ValueError("Nonfinite C5")
    return 0.5 * (c5 + c5.T)


def main(argv: list[str] | None = None) -> int:
    from Numerical.orchestration.GeneralRunningBenchmark import (
        load_canonical_general_exports, run,
    )
    from Numerical.running.SMWeinbergEvolution import (
        SMWeinbergInitialConditions, evolve_sm_weinberg,
    )
    from physics.NeutrinoTrajectory import (
        neutrino_mass_from_c5, charged_lepton_mass_basis_matrix,
    )
    from physics.NeutrinoObservables import calculate_neutrino_observables

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True)
    parser.add_argument("--canonical-run-id", required=True)
    parser.add_argument("--initial-json", type=Path)
    parser.add_argument("--matching-json", type=Path, required=True)
    parser.add_argument("--output-json", type=Path, required=True)
    parser.add_argument("--mu-uv", type=float, default=1e7)
    parser.add_argument("--mu-f", type=float, default=1e5)
    parser.add_argument("--mu-s", type=float, default=1e3)
    parser.add_argument("--mu-low", type=float, default=91.1876)
    parser.add_argument("--vev", type=float, default=246.22)
    parser.add_argument("--ordering", choices=("AUTO", "NO", "IO"), default="AUTO")
    args = parser.parse_args(argv)

    def load(path: Path) -> dict:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        if not isinstance(data, dict):
            raise ValueError(f"Expected JSON object: {path}")
        return data

    matching = load(args.matching_json)
    if matching.get("model") != args.model:
        raise ValueError("Matching model must equal --model")
    uv, eft, provenance = load_canonical_general_exports(args.model, args.canonical_run_id)
    overrides = load(args.initial_json) if args.initial_json else None
    trajectory = run(uv, eft, mu_uv=args.mu_uv, mu_f=args.mu_f,
                     mu_s=args.mu_s, overrides=overrides)
    c5 = construct_c5_from_kernels(trajectory["uv_at_fermion_threshold"], matching)
    # The supplied kernels are defined as C5 at the scalar threshold. The
    # Yukawa flavour structure is evaluated at the heavy-fermion threshold.
    # No higher-dimensional EFT1 operator running is claimed here.
    final = trajectory["eft1_at_scalar_threshold"]
    initial = SMWeinbergInitialConditions(
        gY=float(final["gY"]), g2=float(final["g2"]),
        g3=float(final["g3"]), lambdaH=float(final["lambdaH"]),
        ye=np.asarray(decode(final["ye"]), dtype=complex),
        yu=np.asarray(decode(final["yu"]), dtype=complex),
        yd=np.asarray(decode(final["yd"]), dtype=complex), K=c5,
    ).validated()
    result = evolve_sm_weinberg(initial, args.mu_s, args.mu_low)
    mass = neutrino_mass_from_c5(result.K, vev_gev=args.vev)
    mass = charged_lepton_mass_basis_matrix(mass, result.ye)
    obs = calculate_neutrino_observables(mass, ordering=args.ordering)
    output = {
        "model": args.model,
        "status": "NumericalObservablesWithExternallySuppliedMatchingKernels",
        "full_general_matching_calculated": False,
        "eft1_wilson_rge_calculated": False,
        "matching_coefficients_source": str(args.matching_json),
        "symbolic_provenance": provenance,
        "scales_gev": {"uv": args.mu_uv, "fermion": args.mu_f,
                       "scalar": args.mu_s, "low": args.mu_low},
        "C5_scalar_threshold_gev_inv": encode(c5),
        "C5_low_gev_inv": encode(result.K),
        "neutrino_mass_matrix_gev": encode(mass),
        "neutrino_masses_ev": encode(obs.masses_ev),
        "delta_m21_sq_ev2": obs.delta_m21_sq_ev2,
        "delta_m31_sq_ev2": obs.delta_m31_sq_ev2,
        "delta_m32_sq_ev2": obs.delta_m32_sq_ev2,
        "pmns_abs": encode(obs.pmns_abs),
        "ordering": obs.ordering,
        "takagi_residual": obs.takagi_residual,
        "uv_solver": trajectory["uv_solver"],
        "eft1_solver": trajectory["eft1_solver"],
    }
    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    args.output_json.write_text(json.dumps(output, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    print(f"{args.model}: numerical observables written to {args.output_json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
