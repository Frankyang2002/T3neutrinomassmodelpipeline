"""Build numerical T1/T2/T3 sensitivity scans and HTML for the 5e-9 study.

Modes: individually optimised Yukawas or one shared A(-2) UV Yukawa pair.
The HTML is generated by BuildFittedModelEnvelopes, without any saved
historical HTML template. Scans and old study results are not modified by build.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path
import time

import numpy as np

from Numerical.fitting.BenchmarkSensitivity import run_t3_sensitivity_scan
from Numerical.orchestration import RunLambda5e9Comparisons as compare
from Numerical.orchestration import RunLambda5e9Refit as study
from Numerical.orchestration import RunSmallLambdaRefit as base
from Numerical.plotting import BuildFittedModelEnvelopes as html_generator

ROOT = study.OUT / 'comparison' / 'shared_a_m2' / 'sensitivity'
DIRECTIONS = ('T1', 'T2', 'T3')


def write(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(value, indent=2, allow_nan=False) + '\n', encoding='utf-8')
    temp.replace(path)


def settings(args):
    return {
        'gamma_min': args.gamma_min,
        'gamma_max': args.gamma_max,
        'n_points': args.points,
        'spacing': 'log',
    }


def run(args):
    if not (0 < args.gamma_min < 1 < args.gamma_max):
        raise ValueError('Require gamma_min < 1 < gamma_max with positive gamma_min')
    if args.points < 3 or args.points % 2 != 1:
        raise ValueError('--points must be odd and >= 3')
    shared, models = compare.load_inputs(args.artifact_map, args.mode)
    if args.selected_only:
        comparison = base.load(
            study.OUT / 'comparison'
            / ('shared_a_m2' if args.mode == 'shared' else 'optimised')
            / 'summary.json'
        )['models']
        accepted = {
            item['model'] for item in comparison
            if item.get('status') == 'Success' and item.get('pass_strict_5p86')
        }
        models = [m for m in models if m[0]['model'] in accepted]
    if not models:
        raise ValueError('No selected models')

    config = settings(args)
    fingerprint = hashlib.sha256(
        json.dumps(config, sort_keys=True).encode()
    ).hexdigest()
    records = []
    for k, (row, payload, artifacts) in enumerate(models, 1):
        name = row['model']
        folder = ROOT / name
        result_file = folder / 'sensitivity_diagnostics.json'
        if args.resume and result_file.is_file():
            old = base.load(result_file)
            if old.get('study_sha256') == fingerprint and old.get('status') == 'Success':
                records.append({
                    'model': name, 'status': 'Success',
                    'verified_chi2': old.get('centre_chi2'), 'source': 'Resumed',
                })
                print(f'[{k}/{len(models)}] SKIP {name}: checkpoint exists', flush=True)
                continue
        cfg = copy.deepcopy(payload)
        cfg['sensitivity'] = {'enabled': True, **config}
        started = time.monotonic()
        print(
            f'[{k}/{len(models)}] SCAN {name}: '
            f'3 directions x {args.points} gamma values', flush=True,
        )
        try:
            result = run_t3_sensitivity_scan(
                base_payload=cfg,
                uv_rgbeta_path=artifacts[0],
                intermediate_rgbeta_path=artifacts[1],
                final_weinberg_path=artifacts[2],
                oscillation_target_path=base.TARGET,
            )
            result['model'] = name
            result['study_sha256'] = fingerprint
            result['study_metadata'] = {
                'donor': compare.DONOR if args.mode == 'shared' else name,
                'fixed_lambda': float(cfg['base_state']['ordinary']['lambdaT3']['real']),
                **config,
            }
            middle = []
            for direction in DIRECTIONS:
                points = result['directions'][direction]['points']
                centres = [
                    p for p in points
                    if abs(p['gamma'] - 1.0) < 1e-12
                    and p.get('status') == 'Success'
                ]
                if len(centres) != 1:
                    raise RuntimeError(f'{direction} missing successful gamma=1 centre')
                middle.append(centres[0])
            if not np.allclose(
                [middle[0]['chi2']], [middle[1]['chi2'], middle[2]['chi2']],
                rtol=1e-5, atol=1e-6,
            ):
                raise RuntimeError('Direction centres have inconsistent chi2')
            result['centre_chi2'] = float(middle[0]['chi2'])
            write(result_file, result)
            record = {
                'model': name, 'status': 'Success',
                'verified_chi2': result['centre_chi2'],
                'failed_points': result['n_failed_points'],
            }
            print(
                f'  DONE {name}: chi2(gamma=1)={result["centre_chi2"]:.6g}, '
                f'failed gamma points={result["n_failed_points"]}, '
                f'elapsed={time.monotonic()-started:.1f}s', flush=True,
            )
        except Exception as exc:
            record = {
                'model': name, 'status': 'Failed',
                'message': f'{type(exc).__name__}: {exc}',
            }
            print(f'  FAILED {name}: {record["message"]}', flush=True)
        records.append(record)
        write(ROOT / 'comparison_summary.json', records)
    write(ROOT / 'comparison_summary.json', records)
    print(
        f'Saved {sum(x["status"] == "Success" for x in records)}/{len(records)} '
        f'model scans: {ROOT}', flush=True,
    )


def build(args):
    """Render HTML from the 5e-9 scans using the canonical HTML generator."""
    source = args.source.resolve()
    dest = args.output.resolve()
    if not (source / 'comparison_summary.json').is_file():
        raise FileNotFoundError(
            f'Missing {source / "comparison_summary.json"}. '
            'Run the sensitivity scan first.'
        )
    if dest == source / 'comparison_summary.json':
        raise ValueError('HTML output cannot overwrite the scan summary.')
    data = html_generator.build(source, dest, include_warnings=False)
    # The underlying HTML layout is shared, but make the study and UV input
    # choice explicit instead of labelling the shared-Yukawa case as fitted.
    page = dest.read_text(encoding='utf-8')
    label = (
        'Individually optimised UV Yukawas'
        if args.mode == 'optimised'
        else 'Shared A(-2) UV Yukawas'
    )
    # This label is descriptive; the underlying gamma-scan values are unchanged.
    page = page.replace(
        'Individually fitted T3 model sensitivity',
        f'T3 5e-9 — {label} sensitivity',
    )
    page = page.replace(
        'Fitted T3 prediction-space sensitivity',
        f'T3 5e-9 — {label} prediction-space sensitivity',
    )
    page = page.replace(
        'Each model uses its own fitted λT3, Yukawa matrices and other fitted parameters. Data from saved scans only — no RGE recomputation.',
        ('Each model uses its own fitted UV Yukawa matrices.'
         if args.mode == 'optimised'
         else 'Every model uses identical fitted A(-2) UV Yukawa matrices.')
        + ' Results are from the saved 5e-9 sensitivity scans; no RGE recomputation.',
    )
    dest.write_text(page, encoding='utf-8')
    write(dest.parent / '5e9_sensitivity_display_manifest.json', {
        'generator': 'Numerical.plotting.BuildFittedModelEnvelopes.build',
        'mode': args.mode,
        'input_policy': label,
        'source': str(source),
        'output': str(dest),
        'model_count': len(data['models']),
        'skipped': data['skipped'],
        'warning': 'Empirical gamma-scan envelopes are not parameter confidence regions.',
    })
    print(f'Wrote {dest}; models={len(data["models"])}, skipped={len(data["skipped"])}', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('run', 'build', 'all'))
    parser.add_argument('--mode', choices=('optimised', 'shared'), required=True)
    parser.add_argument('--gamma-min', type=float, default=0.9)
    parser.add_argument('--gamma-max', type=float, default=1.1)
    parser.add_argument('--points', type=int, default=5,
                        help='Odd number of gamma points; first pass defaults to five')
    parser.add_argument('--resume', action='store_true')
    parser.add_argument('--selected-only', action='store_true',
                        help='Only strict-pass models, otherwise all 16')
    parser.add_argument('--artifact-map', type=Path)
    parser.add_argument('--source', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    global ROOT
    ROOT = study.OUT / 'comparison' / (
        'shared_a_m2' if args.mode == 'shared' else 'optimised'
    ) / 'sensitivity'
    if args.source is None:
        args.source = ROOT
    if args.output is None:
        args.output = ROOT.parent / 'envelopes.html'
    if args.action in ('run', 'all'):
        run(args)
    if args.action in ('build', 'all'):
        build(args)


if __name__ == '__main__':
    main()
