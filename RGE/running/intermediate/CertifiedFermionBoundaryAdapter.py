"""Fail-closed adapter for Chat 1's *future* canonical fermion-first handoff.

The interface is intentionally explicit: original Matchete ordered tensor files
are never accepted as canonical. No GammaCC/Weyl factors are guessed.
"""
from __future__ import annotations

from hashlib import sha256
import json
from typing import Any, Mapping

from .GeneralEFT1C5Mixing import FORMAT, CERTIFICATES, BoundaryError, load_boundary

CHAT1_FORMAT = "t3-chat1-canonical-master-weyl-boundary-v1"
CONTEXT_FORMAT = "t3-eft1-renormalizable-couplings-MSbar-v1"


def adapt_chat1_boundary(chat1: Mapping[str, Any],
                         eft1: Mapping[str, Any]) -> dict:
    """Merge certified D5 boundary and scalar/Yukawa/gauge context.

    Chat 1 must provide: {format,model,mu_F_gev,n_fermions,
    n_real_scalars,lepton_components,higgs_real_components,
    canonical_operators:[{source_id,components:[{indices,value}]}],
    certificates:{...}}.

    Other workstream must provide: {format,model,mu_F_gev,mu_S_gev,
    n_fermions,n_real_scalars,lepton_components,higgs_real_components,
    quartic_components,yukawa_components,gauge_sectors,certificates:{...}}
    The certificates are asserted by the responsible workstreams and never
    generated by this adapter.  All nine required certifications must be true.
    """
    if chat1.get("format") != CHAT1_FORMAT:
        raise BoundaryError("Chat 1 must issue its final certified canonical boundary, not ordered data")
    if eft1.get("format") != CONTEXT_FORMAT:
        raise BoundaryError("Missing EFT1 physical quartic/Yukawa/gauge context")
    keys = ("model", "mu_F_gev", "n_fermions", "n_real_scalars",
            "lepton_components", "higgs_real_components", "scalar_field_blocks")
    for key in keys:
        if chat1.get(key) != eft1.get(key):
            raise BoundaryError(f"Chat1/EFT1 contract disagrees on {key}")
    a = chat1.get("certificates", {})
    b = eft1.get("certificates", {})
    if not isinstance(a, dict) or not isinstance(b, dict):
        raise BoundaryError("Each workstream must explicitly supply certifications")
    cert = {name: a.get(name) is True or b.get(name) is True for name in CERTIFICATES}
    # Normalization cannot be vouched for by EFT1 renormalizable-coupling worker.
    for key in ("matchete_gamma_cc_to_weyl_factor_and_sign",
                "canonical_C_ijab_operator_normalization",
                "complete_tree_dim5_operator_inventory",
                "weinberg_C5_symmetric_convention"):
        if a.get(key) is not True:
            raise BoundaryError(f"Only Chat 1 may certify {key}")
    for key in ("complete_EFT1_yukawa_and_gauge_dictionary",
                "complete_scalar_quartic_counterterms",
                "all_heavy_scalar_components_and_mixed_masses",
                "MSbar_subtraction_and_matching_log_partition"):
        if b.get(key) is not True:
            raise BoundaryError(f"Only EFT1 context may certify {key}")
    if not all(cert.values()):
        raise BoundaryError("Some leading-order dim-5 operator classes remain unaudited")
    ops = chat1.get("canonical_operators")
    if not isinstance(ops, list) or not ops:
        raise BoundaryError("Missing Chat1 canonical_operators")
    result = {
        "format": FORMAT, "authority": "certified", "scheme": "MSbar",
        "master_lagrangian_convention": "C_ijab psi_i psi_j phi_a phi_b + hc",
        "weinberg_lagrangian_convention": "(1/2) C5_ij (L_i.H)(L_j.H) + hc",
        **{key: chat1[key] for key in keys},
        "mu_S_gev": eft1.get("mu_S_gev"),
        "operators": ops,
        "quartic_components": eft1.get("quartic_components"),
        "yukawa_components": eft1.get("yukawa_components"),
        "gauge_sectors": eft1.get("gauge_sectors"),
        "certificates": cert,
        "handoff_provenance": {
            "chat1_sha256": sha256(json.dumps(chat1, sort_keys=True).encode()).hexdigest(),
            "eft1_couplings_sha256": sha256(json.dumps(eft1, sort_keys=True).encode()).hexdigest(),
        },
    }
    load_boundary(result)  # Strict structural preflight before writing a file.
    return result
