#!/usr/bin/env python3
"""Generate numerical Section 5.1 text from freshly computed 32-case results.json.

No physics calculation is performed. Tables B1--B4 are generated by the
separate BuildT3GeneralisedThesisTables.py runner from the same result file.
"""
from __future__ import annotations
import argparse
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

MODELS = ('A_-4','A_-2','A_+0','B_-3','B_-1','B_+1','C_-3','C_-1',
          'C_+1','D_-2','D_+0','D_+2','E_-4','E_-2','E_+0','E_+2')
REFS = ('A_-4','D_-2')

def number(value):
    try:
        result = float(value)
        return result if math.isfinite(result) else None
    except (TypeError, ValueError):
        return None

def _fmt(value):
    val = number(value)
    return '--' if val is None else f'{val:.5g}'

def build(root: Path, dest: Path):
    path = root/'results.json'
    if not path.exists():
        raise FileNotFoundError(f'32-case results absent: {path}')
    results = json.loads(path.read_text(encoding='utf-8-sig'))
    for ref in REFS:
        if ref not in results:
            raise ValueError(f'Missing benchmark {ref}')
    prov = json.loads((root/'provenance.json').read_text(encoding='utf-8-sig'))
    entries=[]
    for ref in REFS:
        for model in MODELS:
            r = results[ref].get(model, {})
            obs = r.get('observables') or {}
            entries.append({'reference':ref, 'model':model, 'status':r.get('status'),
                'chi2':number(r.get('chi2')), 'epsilon_C5':number(r.get('epsilon_C5')),
                'k_re':number(r.get('k_re')), 'k_im':number(r.get('k_im')),
                'dm21':number(obs.get('dm21_sq_eV2')),
                'dm31':number(obs.get('dm31_sq_eV2')),
                'theta12':number(obs.get('sin2_theta12')),
                'theta13':number(obs.get('sin2_theta13')),
                'theta23':number(obs.get('sin2_theta23')),
                'error':r.get('error')})
    dest.mkdir(parents=True,exist_ok=True)
    (dest/'representation_analysis.json').write_text(
        json.dumps({'source':str(path),'provenance':prov,'rows':entries},indent=2,allow_nan=False)+'\n',encoding='utf-8')
    completed=[e for e in entries if e['status']=='VALID_EXPLORATORY']
    small=[e for e in completed if e['epsilon_C5'] is not None and e['epsilon_C5']<1e-2]
    lines=['# Section 5.1: representation dependence (new pipeline)', '',
        'These are fixed-Yukawa transfers, NOT independent fits to NuFIT.',
        f'Completed evaluations: {len(completed)}/{len(entries)}.',
        f'Number with relative Frobenius residual epsilon_C5 < 0.01: {len(small)}/{len(completed)}.',
        'Numerical mass splittings and mixing angles are obtained after UV, EFT1 and SMEFT evolution.',
        'All values remain conditional on exploratory matching and Weinberg projection.', '',
        '| Reference | Model | chi2 | Re(k) | Im(k) | epsilon_C5 | dm21 (eV2) | dm31 (eV2) | sin2(theta23) |',
        '|---|---|---:|---:|---:|---:|---:|---:|---:|']
    for e in entries:
        lines.append('| '+' | '.join([e['reference'],e['model'],_fmt(e['chi2']),_fmt(e['k_re']),
            _fmt(e['k_im']),_fmt(e['epsilon_C5']),_fmt(e['dm21']),_fmt(e['dm31']),
            _fmt(e['theta23'])])+' |')
    lines += ['', '## Quantitative comparison by reference', '']
    for ref in REFS:
        subset=[e for e in completed if e['reference']==ref]
        eps=[e['epsilon_C5'] for e in subset if e['epsilon_C5'] is not None]
        smallref=sum(e<0.01 for e in eps)
        chibest=min((e for e in subset if e['chi2'] is not None),
                    key=lambda e:e['chi2'],default=None)
        special={m: next((e for e in subset if e['model']==m),None)
                 for m in ('B_-1','C_-1')}
        lines.append(f'- {ref}: {len(subset)}/16 valid; '
                     f'{smallref}/{len(eps)} with epsilon_C5 < 0.01; '
                     f'epsilon_C5 range {_fmt(min(eps) if eps else None)}–'
                     f'{_fmt(max(eps) if eps else None)}; '
                     f'lowest chi2 model '
                     f'{chibest["model"] if chibest else "N/A"} '
                     f'(chi2={_fmt(chibest["chi2"] if chibest else None)}).')
        for m,e in special.items():
            lines.append(f'  - {m}: epsilon_C5={_fmt(e["epsilon_C5"] if e else None)}, '
                         f'chi2={_fmt(e["chi2"] if e else None)}.')
    lines += ['', '## Interpretation constrained by computed values',
        'The proportionality coefficient k and relative Frobenius residual epsilon_C5 are computed',
        'against the matching reference model *at the same low-energy scale*.',
        'A small epsilon_C5 supports approximate flavour-matrix proportionality;',
        'a large epsilon_C5 indicates a substantial change of matrix structure.',
        'The corresponding mass-squared splittings and mixing angles are given above.',
        'Do not substitute previously published Appendix B or Section 5.1 values.',
        'In particular, B(-1) and C(-1) must be discussed from these new results rather than',
        'assuming the previous pipeline’s proportionality conclusions remain valid.']
    (dest/'Section_5_1_results.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    # Copy-ready LaTeX with a compact, automatically numerical table.
    tex=[r'\subsection*{Representation dependence: updated numerical comparison}',
         'Using the independently evaluated common $A(-4)$ and $D(-2)$ ultraviolet Yukawa benchmarks,',
         'we compare the low-scale Weinberg coefficients after UV, EFT1, and SMEFT evolution.',
         f'The new pipeline completed {len(completed)} of {len(entries)} fixed-Yukawa transfers.',
         'The comparison is conditional on exploratory Wilson-operator projection and matching conventions.',
         r'\begin{table}[htbp]',r'\centering',r'\scriptsize',
         r'\begin{tabular}{llrrrr}',r'\hline',
         r'Reference & Model & $\chi^2$ & $\mathrm{Re}\,k$ & $\mathrm{Im}\,k$ & $\epsilon_{C_5}$ \\',r'\hline']
    for e in entries:
        model=e['model'].replace('_','(')+')'
        ref=e['reference'].replace('_','(')+')'
        tex.append(f'{ref} & {model} & '+ ' & '.join(_fmt(e[k]) for k in ('chi2','k_re','k_im','epsilon_C5'))+r' \\')
    tex += [r'\hline',r'\end{tabular}',
            r'\caption{Representation dependence with fixed reference Yukawa matrices, evaluated with the new exploratory UV--EFT1--SMEFT pipeline.}',
            r'\label{tab:new_generalised_representation}',r'\end{table}']
    (dest/'Section_5_1_results.tex').write_text('\n'.join(tex)+'\n',encoding='utf-8')
    print(f'Section 5.1 results from {len(completed)}/32 successful fixed-Yukawa cases: {dest}',flush=True)

def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--tables',type=Path,required=True)
    p.add_argument('--output',type=Path,default=None)
    args=p.parse_args(argv)
    source=(ROOT/args.tables).resolve()
    dest=(ROOT/args.output).resolve() if args.output else source
    build(source,dest)
    return 0

if __name__=='__main__':
    raise SystemExit(main())
