"""Audit the exact four-barred-doublet DefineCG tensors in A(-4) Matchete traces.

This is a *diagnostic*, not an EFT source transformation. No Matchete
couplings or invariant tensors are overwritten. Does not certify C5.

PowerShell: python -X utf8 -m scripts.DiagnoseT3A4FourDoubletCG --run-dir
  output/parallel_t3/full_general_final_one_batch/<run-id>/A_-4
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import json
from math import sqrt
from pathlib import Path
import re
from typing import Any

TRACE_NAMES = (
    "A_one_loop_DefineCG_calls_DIAGNOSTIC.txt",
    "A_two_heavy_DefineCG_calls_DIAGNOSTIC.txt",
)
COORD = re.compile(r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}")
POINTER = re.compile(r"\{\{\s*0\s*,\s*(\d+)\s*,\s*(\d+)\s*\}\s*,")
NAME = re.compile(r"DefineCG\[\s*([A-Za-z`$][A-Za-z0-9`$]*)\s*,")
WEIGHTS = re.compile(r"\{\s*([^{}]*?)\s*\}\s*\}\s*\]$")


def _balanced_array(s: str) -> str:
    start = s.find("SparseArray[Automatic,")
    if start < 0:
        raise ValueError("No explicit SparseArray[Automatic,...] found")
    depth = 0
    for i in range(start + len("SparseArray"), len(s)):
        if s[i] == "[":
            depth += 1
        elif s[i] == "]":
            depth -= 1
            if depth == 0:
                return s[start:i+1]
    raise ValueError("Unterminated SparseArray in trace")


def _weight(s: str) -> Fraction:
    m = re.fullmatch(r"([+-]?\d+)\s*/\s*Sqrt\[3\]", s.strip())
    if not m:
        raise ValueError(f"Unsupported coefficient (do not guess): {s!r}")
    return Fraction(int(m.group(1)))


def parse_four_bar_tensor(line: str) -> dict[str, Any]:
    """Parse Matchete SparseArray compressed form; values are integer/sqrt(3)."""
    array = _balanced_array(line)
    if not re.search(r"SparseArray\[Automatic,\s*\{\s*2\s*,\s*2\s*,\s*2\s*,\s*2\s*\}", array):
        raise ValueError("Tensor is not 2x2x2x2")
    before = line[:line.find("SparseArray[Automatic,")]
    if before.count("Bar[SU2L[fund]]") != 4:
        raise ValueError("Four Bar[SU2L[fund]] slots required for this audit")
    pointer = POINTER.search(array)
    if not pointer:
        raise ValueError("Unsupported compressed row-pointer layout")
    split = (0, int(pointer.group(1)), int(pointer.group(2)))
    cmatches = COORD.findall(array[pointer.end():])
    if len(cmatches) != split[-1]:
        raise ValueError(f"Expected {split[-1]} triples but found {len(cmatches)}")
    vals = WEIGHTS.search(array)
    if not vals:
        raise ValueError("Cannot locate compressed-array coefficient list")
    numerators = tuple(_weight(v) for v in vals.group(1).split(","))
    if len(numerators) != split[-1]:
        raise ValueError("Coefficient count does not equal compressed-array length")
    components: dict[tuple[int,int,int,int], Fraction] = {}
    for first in (1,2):
        for idx in range(split[first-1], split[first]):
            tail = tuple(int(x) for x in cmatches[idx])
            if not all(1 <= x <= 2 for x in tail):
                raise ValueError("Out-of-range fundamental index")
            key = (first, *tail)
            if key in components:
                raise ValueError("Duplicate tensor component")
            components[key] = numerators[idx]
    match = NAME.search(line)
    return {"name": match.group(1) if match else "UNKNOWN", "components": components}


def _eps(i: int, j: int) -> int:
    return (1 if (i,j)==(1,2) else -1 if (i,j)==(2,1) else 0)


def _dot(a: dict[tuple[int,int,int,int],Fraction], b: dict[tuple[int,int,int,int],int]) -> Fraction:
    return sum((v * b.get(k,0) for k,v in a.items()), Fraction(0))


def audit_tensor(tensor: dict[str, Any]) -> dict[str, Any]:
    """Exact SU(2) maximal-torus test and exact 2d singlet projection.

    Four equally oriented SU(2) doublet slots have exactly two singlets,
    generated by epsilon_ij epsilon_kl and epsilon_ik epsilon_jl.
    Component numerators are fractions with a common denominator sqrt(3).
    """
    comp = tensor["components"]
    if not comp:
        raise ValueError("Empty tensor")
    nonzero = {k:v for k,v in comp.items() if v}
    violations = [k for k in nonzero if k.count(1) != 2]
    keys = [(i,j,k,l) for i in (1,2) for j in (1,2) for k in (1,2) for l in (1,2)]
    b1 = {key: _eps(key[0],key[1])*_eps(key[2],key[3]) for key in keys}
    b2 = {key: _eps(key[0],key[2])*_eps(key[1],key[3]) for key in keys}
    g11 = sum(v*v for v in b1.values()); g22 = sum(v*v for v in b2.values())
    g12 = sum(b1[k]*b2[k] for k in keys)
    det = g11*g22-g12*g12
    if det <= 0:
        raise ValueError("Singlet Gram matrix is singular")
    d1,d2=_dot(comp,b1),_dot(comp,b2)
    p1 = (g22*d1-g12*d2)/det
    p2 = (-g12*d1+g11*d2)/det
    n2=sum((v*v for v in nonzero.values()),Fraction(0))
    projected = (p1*d1+p2*d2)
    fraction = projected / n2 if n2 else Fraction(0)
    # The common 1/sqrt(3) is reinstated in physical norms below.
    return {
        "name": tensor["name"],
        "representations": ["Bar[SU2L[fund]]"]*4,
        "nonzero_components": {"".join(map(str,k)): f"{v}/Sqrt[3]" for k,v in sorted(nonzero.items())},
        "maximal_torus_weight_violations": ["".join(map(str,k)) for k in sorted(violations)],
        "maximal_torus_invariant": not violations,
        "singlet_dimension": 2,
        "singlet_projection_norm_fraction_exact": str(fraction),
        "singlet_projection_norm_fraction": float(fraction),
        "squared_tensor_norm_exact": str(n2 / 3),
        "squared_singlet_projection_norm_exact": str(projected / 3),
        "squared_non_singlet_norm_exact": str((n2-projected)/3),
        "all_su2_invariant": not violations and fraction == 1,
        "matchete_source_version_verified": False,
        "physical_C5_certified": False,
    }


def audit_trace_file(path: Path) -> dict[str, Any]:
    s=path.read_text(encoding="utf-8",errors="backslashreplace")
    lines=[x for x in s.splitlines() if "DefineCG[" in x]
    rows=[]
    for i,line in enumerate(lines,1):
        try:
            rows.append(audit_tensor(parse_four_bar_tensor(line)))
        except ValueError as exc:
            rows.append({"line": i,"unparsed_reason":str(exc),"not_certified":True})
    return {"trace_path":str(path),"DefineCG_calls":len(lines),"four_bar_audits":rows}


def run(run_dir: Path, output: Path) -> dict[str, Any]:
    records=[]
    for name in TRACE_NAMES:
        p=run_dir/name
        if p.is_file():
            records.append(audit_trace_file(p))
    if not records:
        raise FileNotFoundError(f"No A4 DefineCG trace files in {run_dir}")
    accepted=[a for r in records for a in r["four_bar_audits"] if "all_su2_invariant" in a]
    incompatible=any(not a["all_su2_invariant"] for a in accepted)
    result={
        "format":"t3-a4-definecg-fourdoublet-invariance-audit-v10",
        "sources":records,
        "trace_tensor_count_checked":len(accepted),
        "non_invariant_composite_cg_confirmed":incompatible,
        "unparsed_calls":sum(1 for r in records for a in r["four_bar_audits"] if "unparsed_reason" in a),
        "root_cause_source_or_matchete_internal":"UNDETERMINED",
        "safe_automatic_cg_replacement_available":False,
        "source_F_EFT1_equivalence_certified":False,
        "physical_C5_certified":False,
    }
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(json.dumps(result,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    return result


def main(argv: list[str]|None=None)->int:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--run-dir",required=True,type=Path)
    p.add_argument("--output",type=Path)
    a=p.parse_args(argv)
    dest=a.output or a.run_dir/"A_bad_fourdoublet_cg_invariance_audit.json"
    result=run(a.run_dir,dest)
    print("Trace CG calls audited:",result["trace_tensor_count_checked"])
    print("Non-invariant four-doublet tensor:",result["non_invariant_composite_cg_confirmed"])
    print("Unknown-format calls:",result["unparsed_calls"])
    print("Report:",dest)
    return 0 if result["non_invariant_composite_cg_confirmed"] and result["unparsed_calls"]==0 else 3

if __name__=="__main__":
    raise SystemExit(main())
