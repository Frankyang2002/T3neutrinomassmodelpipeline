"""Regenerate the Mathematica quartic manifest from the verified Python enumeration.

The 16-model scalar-sector inventory is a static cross-check, not a
substitute for Matchete's SU(2) contraction validation.

    python scripts/GenerateGeneralScalarWLManifest.py --check
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
JSON_PATH = PROJECT / 'docs/general_scalar_trial_operator_manifest.json'
WL_PATH = PROJECT / 'Lagrangian/interactions/GeneralScalarVerifiedQuartics.wl'
DIMS = {'A': (1, 3), 'B': (2, 2), 'C': (2, 2), 'D': (3, 1), 'E': (3, 3)}


def render() -> str:
    models = json.loads(JSON_PATH.read_text(encoding='utf-8'))['models']
    catalog: dict[str, list[tuple[list[int], int]]] = {}
    for name, data in models.items():
        model, alpha = name.split('_')
        d1, d2 = DIMS[model]
        key = f'{d1}_{d2}_{int(alpha)}'
        entry = [(item['counts'], item['invariants'])
                 for item in data['extra_quartic_structures']]
        if key in catalog and entry != catalog[key]:
            raise ValueError(f'B/C scalar operator manifest disagreement for {key}')
        catalog[key] = entry
    lines: list[str] = []
    for key, entries in catalog.items():
        structure_list = ', '.join(
            '{{' + ', '.join(map(str, counts)) + '}, ' + str(n) + '}'
            for counts, n in entries
        )
        lines.append(f'  "{key}" -> {{{structure_list}}}')
    header = '''(* Verified scalar-quartic structures for the 16 production points.
   This static table is independently generated by the Python SU(2) boson-
   symmetrized operator counter. It contains only monomials whose SU(2)
   symmetric tensor product admits an invariant, and stores the required
   number of independent contractions for each one.

   Key: dS1_dS2_alpha. B/C share dS1=dS2=2 and hence the same scalar
   operator counts, independent of dF. These are PER-MODEL structures.

   This guards against false-success audits in which the Wolfram
   hypercharge enumeration silently misses an allowed structure.
   General higher-dimensional forced DIMS models still use the dynamic
   enumeration and are NOT certified by this 16-model manifest.
*)

ClearAll[T3ExtendedVerifiedQuarticTable, T3ExtendedVerifiedEntries];

T3ExtendedVerifiedQuarticTable = <|
'''
    footer = '''
|>;

T3ExtendedVerifiedEntries[model_Association] := Module[{key},
  key = StringRiffle[ToString /@ {
    model["Scalar1", "SU2"], model["Scalar2", "SU2"], model["Alpha"]
  }, "_"];
  Lookup[T3ExtendedVerifiedQuarticTable, key, Missing["UncertifiedModel", key]]
];
'''
    return header + ',\n'.join(lines) + footer


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if WL table is out of date')
    args = parser.parse_args()
    result = render()
    if args.check:
        success = WL_PATH.is_file() and WL_PATH.read_text(encoding='utf-8') == result
        print(f'Mathematica quartic manifest sync: {"OK" if success else "STALE"}')
        return 0 if success else 1
    WL_PATH.write_text(result, encoding='utf-8')
    print(f'Updated {WL_PATH}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
