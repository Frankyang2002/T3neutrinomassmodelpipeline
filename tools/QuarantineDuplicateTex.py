"""Reversibly quarantine SHA-256-identical TeX report copies.

Run from the repository root:
    python -m tools.QuarantineDuplicateTex
    python -m tools.QuarantineDuplicateTex --apply
    python -m tools.QuarantineDuplicateTex --restore

Consumes duplicate_tex_audit.csv generated by AuditDuplicateTex.py.
No symbolic or numerical calculations are performed.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_AUDIT = PROJECT_ROOT / 'duplicate_tex_audit.csv'
DEFAULT_QUARANTINE = PROJECT_ROOT / '.cleanup_quarantine' / 'duplicate_tex'
DEFAULT_PREVIEW = PROJECT_ROOT / 'duplicate_tex_quarantine_preview.csv'


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def inside(path: Path, parent: Path) -> bool:
    return path == parent or parent in path.parents


def resolve_audit_path(raw: str) -> Path:
    path = Path(raw.strip())
    return path.resolve() if path.is_absolute() else (PROJECT_ROOT / path).resolve()


def read_candidates(audit: Path, quarantine: Path):
    report_root = (PROJECT_ROOT / 'Reports' / 'output' / 'full').resolve()
    if not audit.is_file():
        raise FileNotFoundError(f'Missing audit: {audit}; run python -m tools.AuditDuplicateTex first')
    candidates = []
    with audit.open(newline='', encoding='utf-8-sig') as stream:
        reader = csv.DictReader(stream)
        required = {'classification', 'path', 'canonical_path'}
        if not required.issubset(reader.fieldnames or []):
            raise ValueError(f'Audit columns missing: {sorted(required - set(reader.fieldnames or []))}')
        for lineno, row in enumerate(reader, 2):
            if row['classification'] != 'EXACT_DUPLICATE':
                continue
            source = resolve_audit_path(row['path'])
            canonical = resolve_audit_path(row['canonical_path'])
            if (not inside(source, report_root) or not inside(canonical, report_root)
                    or inside(source, quarantine) or inside(canonical, quarantine)
                    or source.suffix.lower() != '.tex' or canonical.suffix.lower() != '.tex'
                    or source == canonical):
                raise ValueError(f'Unsafe or invalid audit path on line {lineno}: {source}')
            candidates.append((source, canonical))
    if len({src for src, _ in candidates}) != len(candidates):
        raise ValueError('Duplicate source paths in audit')
    return candidates


def validate(candidates, quarantine):
    good = []
    skipped = []
    for source, canonical in candidates:
        if not source.is_file() or not canonical.is_file():
            skipped.append((source, 'source or canonical missing'))
            continue
        try:
            source_hash = sha256(source)
            canonical_hash = sha256(canonical)
        except OSError as exc:
            skipped.append((source, f'unreadable: {exc}'))
            continue
        if source_hash != canonical_hash:
            skipped.append((source, 'hash mismatch; audit stale'))
            continue
        dest = quarantine / source.relative_to(PROJECT_ROOT)
        if dest.exists():
            skipped.append((source, 'quarantine destination already exists'))
            continue
        good.append({'source': str(source), 'canonical': str(canonical),
                     'destination': str(dest), 'sha256': source_hash,
                     'bytes': source.stat().st_size})
    return good, skipped


def preview(rows, skipped, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', newline='', encoding='utf-8') as stream:
        writer = csv.DictWriter(stream, fieldnames=['status', 'source', 'canonical', 'bytes', 'sha256', 'reason'])
        writer.writeheader()
        for row in rows:
            writer.writerow({'status': 'ELIGIBLE', 'source': row['source'],
                             'canonical': row['canonical'], 'bytes': row['bytes'],
                             'sha256': row['sha256'], 'reason': ''})
        for source, reason in skipped:
            writer.writerow({'status': 'SKIPPED', 'source': str(source), 'reason': reason})


def apply(rows, quarantine):
    manifest = quarantine / 'manifest.json'
    if manifest.exists():
        raise FileExistsError(f'Existing quarantine manifest: {manifest}. Restore it before a new apply.')
    quarantine.mkdir(parents=True, exist_ok=True)
    moved = []
    try:
        for row in rows:
            source = Path(row['source'])
            canonical = Path(row['canonical'])
            dest = Path(row['destination'])
            if not source.is_file() or not canonical.is_file() or sha256(source) != row['sha256'] or sha256(canonical) != row['sha256']:
                raise RuntimeError(f'Changed during execution: {source}')
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(source), str(dest))
            moved.append(row)
            # Persist after each move so an interruption remains recoverable.
            manifest.write_text(json.dumps({'version': 1, 'created_utc': datetime.now(timezone.utc).isoformat(),
                                            'project_root': str(PROJECT_ROOT), 'files': moved}, indent=2) + '\n', encoding='utf-8')
    except Exception:
        # Manifest survives if any move happened; do not mask the underlying exception.
        raise
    print(f'Quarantined {len(moved)} exact duplicates. Manifest: {manifest}')


def restore(quarantine):
    manifest = quarantine / 'manifest.json'
    if not manifest.is_file():
        raise FileNotFoundError(f'Missing restore manifest: {manifest}')
    record = json.loads(manifest.read_text(encoding='utf-8'))
    if record.get('project_root') != str(PROJECT_ROOT):
        raise ValueError('Manifest belongs to another project root')
    entries = record['files']
    restored = 0
    for row in reversed(entries):
        source = Path(row['source']).resolve()
        dest = Path(row['destination']).resolve()
        if not inside(source, (PROJECT_ROOT / 'Reports' / 'output' / 'full').resolve()) or not inside(dest, quarantine):
            raise ValueError(f'Unsafe restore path: {source}')
        if source.exists():
            print(f'SKIP occupied original path: {source}')
            continue
        if not dest.is_file() or sha256(dest) != row['sha256']:
            print(f'SKIP missing or modified quarantine file: {dest}')
            continue
        source.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(dest), str(source))
        restored += 1
    remaining = [row for row in entries if Path(row['destination']).exists()]
    if remaining:
        record['files'] = remaining
        manifest.write_text(json.dumps(record, indent=2) + '\n', encoding='utf-8')
    else:
        manifest.unlink()
    print(f'Restored {restored}; remaining quarantined: {len(remaining)}')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    operation = parser.add_mutually_exclusive_group()
    operation.add_argument('--apply', action='store_true')
    operation.add_argument('--restore', action='store_true')
    parser.add_argument('--audit', type=Path, default=DEFAULT_AUDIT)
    parser.add_argument('--quarantine', type=Path, default=DEFAULT_QUARANTINE)
    parser.add_argument('--preview', type=Path, default=DEFAULT_PREVIEW)
    args = parser.parse_args(argv)
    quarantine = args.quarantine.resolve()
    if not inside(quarantine, (PROJECT_ROOT / '.cleanup_quarantine').resolve()):
        parser.error('Quarantine must be inside PROJECT_ROOT/.cleanup_quarantine')
    if args.restore:
        restore(quarantine)
        return 0
    candidates = read_candidates(args.audit.resolve(), quarantine)
    valid, skipped = validate(candidates, quarantine)
    preview(valid, skipped, args.preview.resolve())
    print(f'Audit candidates: {len(candidates)}; hash verified: {len(valid)}; skipped: {len(skipped)}')
    print(f'Preview: {args.preview.resolve()}')
    if args.apply:
        if skipped:
            parser.error('Refusing partial apply: audit changed or unsafe destinations; inspect skipped rows first')
        apply(valid, quarantine)
    else:
        print('Dry run only. Use --apply after reviewing the preview.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
