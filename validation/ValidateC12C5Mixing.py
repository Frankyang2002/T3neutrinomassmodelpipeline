"""Validate the one-generation C12/C5 symbolic mixing audit.

Uses the two-seed audit JSON as input. Extracts the four anomalous-dimension
blocks in canonical coordinates:
    C12 = (conjugate(y1)*conjugate(y2)/MF) * T12
    C5 = kappa * T5
and optionally compares the direct C12->C5 beta with the production
eft1_wilson_rge.json Weinberg diagnostic.

This tests internal algebra and existing production consistency, NOT an
independent field-theoretic derivation of the master anomalous dimension.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import sympy as sp

KAPPA = sp.Symbol("kappa")
Y1, Y2, MF = sp.symbols("y1 y2 MF")
S = sp.conjugate(Y1) * sp.conjugate(Y2) / MF
LAM_T3 = sp.Symbol("lambdaT3")

def parse(raw):
    return sp.sympify(str(raw), locals={"conjugate": sp.conjugate, "I": sp.I,
                                      "sqrt": sp.sqrt, "kappa": KAPPA})

def equal(a, b):
    return sp.simplify(a - b) == 0

def ratio(audit, source, target):
    return parse(audit["mixing"][source][target]["proportionality_factor"])

def extract_matrix(audit):
    block = audit.get("mixing", {})
    for source in ("C12_only", "C5_only"):
        for target in ("LLSS", "C5_HH", "mixed_HS"):
            item = block[source][target]
            if item["proportionality_residual_count"] != 0:
                raise ValueError(f"Non-closed operator direction {source}->{target}: "
                                 f"{item['proportionality_residual_count']} residuals")
            if target == "mixed_HS" and item["nonzero_target_components"]:
                raise ValueError(f"Additional mixed H/S operators generated by {source}")
    # The ratio for C12_only -> C5_HH is beta_kappa/kappa,
    # and for C5_only -> LLSS is beta_s/s.
    g1212 = ratio(audit, "C12_only", "LLSS")
    g5512 = sp.cancel(ratio(audit, "C12_only", "C5_HH") * KAPPA / S)
    g125 = sp.cancel(ratio(audit, "C5_only", "LLSS") * S / KAPPA)
    g55 = ratio(audit, "C5_only", "C5_HH")
    forbidden = {KAPPA, Y1, Y2, MF}
    for name, value in {"g1212": g1212, "g125": g125,
                        "g5512": g5512, "g55": g55}.items():
        if any(value.has(v, sp.conjugate(v)) for v in forbidden):
            raise ValueError(f"{name} still depends on Wilson seed parameters: {value}")
    return {"gamma_12_12": sp.simplify(g1212),
            "gamma_12_5": sp.simplify(g125),
            "gamma_5_12": sp.simplify(g5512),
            "gamma_5_5": sp.simplify(g55)}

def validate(audit, production=None):
    mat = extract_matrix(audit)
    checks = {}
    checks["forward_lambdaT3"] = equal(
        mat["gamma_5_12"], 4*sp.sqrt(3)*LAM_T3/3)
    checks["reverse_conjugate_lambdaT3"] = equal(
        mat["gamma_12_5"], 8*sp.sqrt(3)*sp.conjugate(LAM_T3)/3)
    checks["offdiagonal_factor_two"] = equal(
        mat["gamma_12_5"], 2*sp.conjugate(mat["gamma_5_12"]))
    checks["both_offdiagonal_nonzero"] = (
        mat["gamma_12_5"] != 0 and mat["gamma_5_12"] != 0
    )
    checks["all_audit_proportionality_residuals_zero"] = all(
        audit["mixing"][src][tgt]["proportionality_residual_count"] == 0
        for src in ("C12_only", "C5_only")
        for tgt in ("C5_HH", "LLSS", "mixed_HS")
    )
    checks["no_mixed_HS_outputs"] = all(
        audit["mixing"][src]["mixed_HS"]["nonzero_target_components"] == 0
        for src in ("C12_only", "C5_only")
    )
    prod_details = {"status": "not_provided"}
    if production is not None:
        diagnostic = production.get("weinberg_subspace_validation") or {}
        if "beta_kappa_16pi2" not in diagnostic:
            raise ValueError("Production JSON lacks Weinberg beta diagnostic")
        production_beta = parse(diagnostic["beta_kappa_16pi2"])
        audit_beta = sp.simplify(mat["gamma_5_12"] * S)
        checks["production_forward_matches_audit"] = equal(
            production_beta, audit_beta
        )
        prod_details = {
            "status": "checked",
            "production_beta_kappa": sp.sstr(production_beta),
            "audit_beta_kappa": sp.sstr(audit_beta),
        }
    # The adapter creates quartic symbols from Matchete's coupling names.
    # No claim about their numerical mapping is made by this tool.
    scalar_symbol_names = sorted({
        symbol.name for name in ("gamma_12_12", "gamma_12_5",
                                "gamma_5_12", "gamma_5_5")
        for symbol in mat[name].free_symbols
    })
    unresolved_higgs_quartic = "λ" in scalar_symbol_names
    return {
        "status": "ChecksPassed" if all(checks.values()) else "ChecksFailed",
        "scope": "one-generation algebraic/source consistency only",
        "anomalous_dimension_matrix": {
            name: sp.sstr(value) for name, value in mat.items()
        },
        "checks": checks,
        "production_comparison": prod_details,
        "scalar_symbols": scalar_symbol_names,
        "higgs_quartic_mapping": {
            "status": "requires_explicit_mapping" if unresolved_higgs_quartic
                      else "no_unicode_lambda_detected",
            "note": ("The quartic tensor adapter uses original Matchete coupling "
                     "names. Do not identify λ with lambdaH without checking "
                     "the model/exported seed and numerical RGBeta dictionary.")
        },
        "independent_physics_normalization_verified": False,
        "full_flavor_closure_verified": False,
    }

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audit", required=True, type=Path)
    parser.add_argument("--production-rge", type=Path, default=None)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    audit = json.loads(args.audit.read_text(encoding="utf-8"))
    production = (json.loads(args.production_rge.read_text(encoding="utf-8"))
                  if args.production_rge else None)
    result = validate(audit, production)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps(result, indent=2))
    raise SystemExit(0 if result["status"] == "ChecksPassed" else 1)

if __name__ == "__main__":
    main()
